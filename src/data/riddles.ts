export function normalizeArabic(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/[إأآٱA-Z]/g, (m) => (m === 'إ' || m === 'أ' || m === 'آ' || m === 'ٱ' ? 'ا' : m.toLowerCase()))
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[^\w\sء-ي]/g, '')
    .replace(/\s+/g, '');
}

export function checkAnswer(userAnswer: string, riddle: Riddle): boolean {
  const normUser = normalizeArabic(userAnswer);
  if (!normUser) return false;
  
  const allAccepted = [riddle.answer, ...riddle.acceptedAnswers];
  return allAccepted.some((ans) => normalizeArabic(ans) === normUser);
}

